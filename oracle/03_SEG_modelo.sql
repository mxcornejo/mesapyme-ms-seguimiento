-- Propietario: MP_SEG. No ejecutar en esquemas ajenos.

CREATE TABLE ticket_proyeccion (
  solicitud_id NUMBER PRIMARY KEY,
  titulo VARCHAR2(150 CHAR) NOT NULL,
  solicitante_sub VARCHAR2(255 CHAR) NOT NULL,
  tecnico_sub VARCHAR2(255 CHAR),
  tecnico_nombre VARCHAR2(150 CHAR),
  categoria_nombre VARCHAR2(100 CHAR) NOT NULL,
  prioridad VARCHAR2(10 CHAR) NOT NULL,
  estado VARCHAR2(25 CHAR) NOT NULL,
  creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
  vence_en TIMESTAMP WITH TIME ZONE NOT NULL,
  resuelta_en TIMESTAMP WITH TIME ZONE,
  version_origen NUMBER NOT NULL,
  sincronizada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (estado IN ('NUEVA','ASIGNADA','EN_ATENCION','ESPERA_ANTECEDENTES','RESUELTA','CERRADA','CANCELADA')),
  CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
  CHECK (version_origen >= 1)
);

CREATE TABLE evento_recibido (
  event_id VARCHAR2(36 CHAR) PRIMARY KEY,
  tipo VARCHAR2(60 CHAR) NOT NULL,
  solicitud_id NUMBER NOT NULL,
  version_origen NUMBER NOT NULL,
  procesado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE escalamiento (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id NUMBER NOT NULL UNIQUE,
  evento_id VARCHAR2(36 CHAR) NOT NULL UNIQUE REFERENCES evento_recibido(event_id),
  vencio_en TIMESTAMP WITH TIME ZONE NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  pendiente NUMBER(1) DEFAULT 1 NOT NULL,
  CHECK (pendiente IN (0,1))
);

CREATE TABLE alerta (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escalamiento_id NUMBER NOT NULL UNIQUE REFERENCES escalamiento(id),
  destino_rol VARCHAR2(15 CHAR) DEFAULT 'ADMINISTRADOR' NOT NULL,
  mensaje VARCHAR2(500 CHAR) NOT NULL,
  creada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (destino_rol = 'ADMINISTRADOR')
);

CREATE TABLE seguimiento (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escalamiento_id NUMBER NOT NULL REFERENCES escalamiento(id),
  admin_sub VARCHAR2(255 CHAR) NOT NULL,
  accion VARCHAR2(2000 CHAR) NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_proy_filters ON ticket_proyeccion(estado, prioridad, tecnico_sub);
CREATE INDEX ix_esc_pending ON escalamiento(pendiente, creado_en);
CREATE INDEX ix_seg_esc ON seguimiento(escalamiento_id, creado_en);
